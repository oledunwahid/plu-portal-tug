// ── PLURequest filter builder ────────────────────────────────────────────────

function buildPLUConditions(filters: PLURequestFilters, alias: string): { conditions: string[]; params: unknown[] } {
  const conditions: string[] = [];
  const params: unknown[] = [];
  if (filters.status && filters.status !== 'ALL')           { conditions.push(`${alias}.status = ?`);       params.push(filters.status); }
  if (filters.outletGroup && filters.outletGroup !== 'ALL') { conditions.push(`${alias}.outletGroup = ?`);  params.push(filters.outletGroup); }
  if (filters.requestType && filters.requestType !== 'ALL') { conditions.push(`${alias}.requestType = ?`);  params.push(filters.requestType); }
  if (filters.userId)                                        { conditions.push(`${alias}.userId = ?`);      params.push(filters.userId); }
  if (filters.from) {
    conditions.push(`${alias}.createdAt >= ?`);
    params.push(filters.from);
  }
  if (filters.to) {
    const d = new Date(filters.to); d.setHours(23, 59, 59, 999);
    conditions.push(`${alias}.createdAt <= ?`);
    params.push(d.toISOString());
  }
  if (filters.ids && filters.ids.length > 0) {
    conditions.push(`${alias}.id IN (${filters.ids.map(() => '?').join(',')})`);
    params.push(...filters.ids);
  }
  if (filters.search && filters.search.trim()) {
    // Admin free-text search. SQLite LIKE is case-insensitive for ASCII, so no upper() needed.
    // UPDATE_PRICE / UPDATE_NAME rows carry no item name of their own - the displayed name comes
    // from the master registry, so the search reaches into MasterItem via the request's code.
    const q = `%${filters.search.trim()}%`;
    conditions.push(`(
      ${alias}.id LIKE ? OR ${alias}.code LIKE ? OR ${alias}.name LIKE ?
      OR ${alias}.category LIKE ? OR ${alias}.department LIKE ?
      OR ${alias}.cashierOutlet LIKE ? OR ${alias}.outletGroup LIKE ?
      OR ${alias}.barcode LIKE ? OR ${alias}.confirmedBarcode LIKE ? OR ${alias}.suggestedBarcode LIKE ?
      OR ${alias}.status LIKE ? OR ${alias}.exportBatchId LIKE ?
      OR EXISTS (SELECT 1 FROM "User" su WHERE su.id = ${alias}.userId AND (su.name LIKE ? OR su.outlet LIKE ?))
      OR EXISTS (SELECT 1 FROM "MasterItem" smi WHERE smi.code = ${alias}.code
                 AND (smi.name LIKE ? OR smi.category LIKE ? OR smi.barcode LIKE ? OR smi.plu LIKE ?))
    )`);
    params.push(...new Array(18).fill(q));
  }
  return { conditions, params };
}

