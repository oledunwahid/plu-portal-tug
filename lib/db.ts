// ── Notification feed (admin bell) ────────────────────────────────────────────
// Notifications are sourced live from the request tables; only read-state is stored
// (NotificationRead). The feed merges single PLURequest + batch RequestBatch rows,
// newest first, and is consumed by /api/admin/notifications.

export interface AdminNotification {
  id: string;
  source: 'single' | 'batch';
  requestType: string;
  title: string;
  itemCount: number; // batch only; 0 for singles
  createdAt: string;
  submittedByName: string;
  submittedByOutlet: string;
}

// Notification feed scope. ADMIN sees the full queue (every request/batch, including any edge-case
// PENDING_COST_CONTROL rows); COST_CONTROL sees ONLY the items awaiting it (single PENDING_COST_CONTROL requests —
// cost control never handles batches); CASHIER sees ONLY their own DONE requests/batches ("ready to
// sync"). All three reuse the same NotificationRead read-state mechanism. For CASHIER, `userId` MUST
// be supplied so the feed is strictly scoped to the requester's own items.
export type NotificationScope = 'ADMIN' | 'COST_CONTROL' | 'CASHIER';

// Merged, newest-first slice of single + batch requests with submitter info.
export async function getAdminNotificationFeed(
  limit: number, offset: number, scope: NotificationScope = 'ADMIN', userId?: string,
): Promise<AdminNotification[]> {
  try {
    const db = await getDb();
    if (scope === 'CASHIER') {
      // The cashier "Siap Sync" feed: their own single + batch requests that admin has marked DONE,
      // newest-DONE first. Ordered by doneAt so the entry reflects when it became ready to sync.
      if (!userId) return [];
      const rows = execAll(db, `
        SELECT t.id, t.source, t.requestType, t.title, t.itemCount, t.createdAt,
               u.name as u_name, u.outlet as u_outlet
        FROM (
          SELECT pr.id AS id, 'single' AS source, pr.requestType AS requestType,
                 pr.name AS title, 0 AS itemCount,
                 COALESCE(pr.doneAt, pr.updatedAt, pr.createdAt) AS createdAt, pr.userId AS userId
          FROM "PLURequest" pr
          WHERE pr.userId = ? AND pr.status = 'DONE'
          UNION ALL
          SELECT rb.id, 'batch', rb.requestType, rb.title,
                 (SELECT COUNT(*) FROM "RequestBatchItem" ri WHERE ri.batchId = rb.id),
                 COALESCE(rb.doneAt, rb.updatedAt, rb.createdAt), rb.userId
          FROM "RequestBatch" rb
          WHERE rb.userId = ? AND rb.status = 'DONE'
        ) t
        LEFT JOIN "User" u ON t.userId = u.id
        ORDER BY t.createdAt DESC
        LIMIT ? OFFSET ?
      `, [userId, userId, limit, offset]);
      return rows.map((r) => ({
        id: String(r.id),
        source: r.source === 'batch' ? 'batch' : 'single',
        requestType: String(r.requestType),
        title: String(r.title ?? ''),
        itemCount: Number(r.itemCount ?? 0),
        createdAt: String(r.createdAt),
        submittedByName: String(r.u_name ?? ''),
        submittedByOutlet: String(r.u_outlet ?? ''),
      }));
    }
    if (scope === 'COST_CONTROL') {
      const ccRows = execAll(db, `
        SELECT pr.id AS id, pr.requestType AS requestType, pr.name AS title,
               pr.createdAt AS createdAt, u.name AS u_name, u.outlet AS u_outlet
        FROM "PLURequest" pr LEFT JOIN "User" u ON pr.userId = u.id
        WHERE pr.status = 'PENDING_COST_CONTROL'
        ORDER BY pr.createdAt DESC LIMIT ? OFFSET ?
      `, [limit, offset]);
      return ccRows.map((r) => ({
        id: String(r.id),
        source: 'single' as const,
        requestType: String(r.requestType),
        title: String(r.title ?? ''),
        itemCount: 0,
        createdAt: String(r.createdAt),
        submittedByName: String(r.u_name ?? ''),
        submittedByOutlet: String(r.u_outlet ?? ''),
      }));
    }
    const rows = execAll(db, `
      SELECT t.id, t.source, t.requestType, t.title, t.itemCount, t.createdAt,
             u.name as u_name, u.outlet as u_outlet
      FROM (
        SELECT pr.id AS id, 'single' AS source, pr.requestType AS requestType,
               pr.name AS title, 0 AS itemCount, pr.createdAt AS createdAt, pr.userId AS userId
        FROM "PLURequest" pr
        UNION ALL
        SELECT rb.id, 'batch', rb.requestType, rb.title,
               (SELECT COUNT(*) FROM "RequestBatchItem" ri WHERE ri.batchId = rb.id),
               rb.createdAt, rb.userId
        FROM "RequestBatch" rb
      ) t
      LEFT JOIN "User" u ON t.userId = u.id
      ORDER BY t.createdAt DESC
      LIMIT ? OFFSET ?
    `, [limit, offset]);
    return rows.map((r) => ({
      id: String(r.id),
      source: r.source === 'batch' ? 'batch' : 'single',
      requestType: String(r.requestType),
      title: String(r.title ?? ''),
      itemCount: Number(r.itemCount ?? 0),
      createdAt: String(r.createdAt),
      submittedByName: String(r.u_name ?? ''),
      submittedByOutlet: String(r.u_outlet ?? ''),
    }));
  } catch (err) {
    console.error('[db] getAdminNotificationFeed failed:', err);
    return [];
  }
}

// IDs of the most recent `scanLimit` requests (single + batch merged). Used to bound
// the unread count and "mark all as read" to recent activity rather than full history.
export async function getRecentRequestIds(
  scanLimit: number, scope: NotificationScope = 'ADMIN', userId?: string,
): Promise<string[]> {
  try {
    const db = await getDb();
    if (scope === 'CASHIER') {
      if (!userId) return [];
      const rows = execAll(db, `
        SELECT id FROM (
          SELECT id, COALESCE(doneAt, updatedAt, createdAt) AS ts FROM "PLURequest" WHERE userId = ? AND status = 'DONE'
          UNION ALL
          SELECT id, COALESCE(doneAt, updatedAt, createdAt) AS ts FROM "RequestBatch" WHERE userId = ? AND status = 'DONE'
        ) ORDER BY ts DESC LIMIT ?
      `, [userId, userId, scanLimit]);
      return rows.map((r) => String(r.id));
    }
    if (scope === 'COST_CONTROL') {
      const ccRows = execAll(db,
        `SELECT id FROM "PLURequest" WHERE status = 'PENDING_COST_CONTROL' ORDER BY createdAt DESC LIMIT ?`,
        [scanLimit]);
      return ccRows.map((r) => String(r.id));
    }
    const rows = execAll(db, `
      SELECT id FROM (
        SELECT id, createdAt FROM "PLURequest"
        UNION ALL
        SELECT id, createdAt FROM "RequestBatch"
      ) ORDER BY createdAt DESC LIMIT ?
    `, [scanLimit]);
    return rows.map((r) => String(r.id));
  } catch (err) {
    console.error('[db] getRecentRequestIds failed:', err);
    return [];
  }
}

