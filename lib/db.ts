// ── DB init ──────────────────────────────────────────────────────────────────

function resolveDbPath(): string {
  const url = process.env.DATABASE_URL ?? 'file:./dev.db';
  const filePart = url.replace(/^file:/, '');
  if (path.isAbsolute(filePart)) return filePart;
  return path.resolve(process.cwd(), filePart);
}

// eslint-disable-next-line @typescript-eslint/no-explicit-any
const g = globalThis as unknown as { __sqljsDb?: any; __sqljsSql?: any; __sqljsInit?: Promise<any> };

// Build + migrate the sql.js database on a LOCAL handle, publishing it to
// g.__sqljsDb only once fully migrated. Callers reach this through getDb()'s
// shared init promise, so concurrent requests (e.g. the stats route firing
// dozens of counts at once on a cold start) never trigger overlapping reads,
// migrations, or writeFileSync calls - which previously raced and could be
// killed under cPanel resource limits, surfacing as an all-zero dashboard.
async function initDb(): Promise<any> {
  const dbPath = resolveDbPath();
  if (!fs.existsSync(dbPath)) throw new Error(`DB file not found: ${dbPath}`);
  if (!g.__sqljsSql) {
    g.__sqljsSql = await initSqlJs({
      locateFile: () => path.join(process.cwd(), 'public', 'sql-wasm.wasm'),
    });
  }
  const db = new g.__sqljsSql.Database(fs.readFileSync(dbPath));
  // Schema migrations - idempotent, silently ignored if column already exists
  try { db.run('ALTER TABLE "PLURequest" ADD COLUMN "codeIsAutoGenerated" INTEGER NOT NULL DEFAULT 1'); } catch { /* already exists */ }
  try { db.run('ALTER TABLE "RequestBatchItem" ADD COLUMN "codeIsAutoGenerated" INTEGER NOT NULL DEFAULT 1'); } catch { /* already exists */ }
  try { db.run('ALTER TABLE "PLURequest" ADD COLUMN "barcode" TEXT'); } catch { /* already exists */ }
  try { db.run('ALTER TABLE "RequestBatchItem" ADD COLUMN "barcode" TEXT'); } catch { /* already exists */ }
  // Cost Control approval stage (WINE NEW_ITEM from Cork outlets). suggestedBarcode is the
  // system's NCK-derived guess at submission time; confirmedBarcode is what cost control saved
  // after review. Both nullable - only the cost-control flow ever populates them.
  try { db.run('ALTER TABLE "PLURequest" ADD COLUMN "suggestedBarcode" TEXT'); } catch { /* already exists */ }
  try { db.run('ALTER TABLE "PLURequest" ADD COLUMN "confirmedBarcode" TEXT'); } catch { /* already exists */ }
  // Source label for suggestedBarcode - tells cost control whether the suggestion came from a real
  // SAP NCK match or is a system-generated sequential value needing extra scrutiny. Nullable.
  try { db.run('ALTER TABLE "PLURequest" ADD COLUMN "suggestedBarcodeSource" TEXT'); } catch { /* already exists */ }
  try { db.run('ALTER TABLE "RequestBatchItem" ADD COLUMN "remarks" TEXT'); } catch { /* already exists */ }
  // Audit trail - who last changed the record
  try { db.run('ALTER TABLE "PLURequest" ADD COLUMN "updatedBy" TEXT'); } catch { /* already exists */ }
  try { db.run('ALTER TABLE "RequestBatch" ADD COLUMN "updatedBy" TEXT'); } catch { /* already exists */ }
  try { db.run('ALTER TABLE "DiscountRequest" ADD COLUMN "updatedBy" TEXT'); } catch { /* already exists */ }
  // Export tracking - EXPORTED status + how many times / when / by whom each record was downloaded
  try { db.run('ALTER TABLE "PLURequest" ADD COLUMN "exportCount" INTEGER NOT NULL DEFAULT 0'); } catch { /* already exists */ }
  try { db.run('ALTER TABLE "PLURequest" ADD COLUMN "lastExportedAt" TEXT'); } catch { /* already exists */ }
  try { db.run('ALTER TABLE "PLURequest" ADD COLUMN "lastExportedBy" TEXT'); } catch { /* already exists */ }
  try { db.run('ALTER TABLE "RequestBatch" ADD COLUMN "exportCount" INTEGER NOT NULL DEFAULT 0'); } catch { /* already exists */ }
  try { db.run('ALTER TABLE "RequestBatch" ADD COLUMN "lastExportedAt" TEXT'); } catch { /* already exists */ }
  try { db.run('ALTER TABLE "RequestBatch" ADD COLUMN "lastExportedBy" TEXT'); } catch { /* already exists */ }
  // ── Wine List module: account identity ──────────────────────────────────────
  // `role` stays untouched (a Wine PIC is still CASHIER-like for every existing request flow);
  // accountType is the additive business-identity flag ('WINE_PIC' for the Wine Cork account) and
  // businessUnit its brand label ('Wine Cork'), used for branding + Wine List access. winePermissions
  // holds an optional explicit grant list (semicolon-separated, or 'ALL') so a non-WINE_PIC user can
  // be given Wine List access for maintenance without changing their role.
  try { db.run('ALTER TABLE "User" ADD COLUMN "accountType" TEXT'); } catch { /* already exists */ }
  try { db.run('ALTER TABLE "User" ADD COLUMN "businessUnit" TEXT'); } catch { /* already exists */ }
  try { db.run('ALTER TABLE "User" ADD COLUMN "winePermissions" TEXT'); } catch { /* already exists */ }
  // Publication stamps - a DONE wine request may be published to the Wine List exactly once.
  try { db.run('ALTER TABLE "PLURequest" ADD COLUMN "publishedToWineList" INTEGER NOT NULL DEFAULT 0'); } catch { /* already exists */ }
  try { db.run('ALTER TABLE "PLURequest" ADD COLUMN "publishedAt" TEXT'); } catch { /* already exists */ }
  try { db.run('ALTER TABLE "PLURequest" ADD COLUMN "publishedBy" TEXT'); } catch { /* already exists */ }
  // KB tables
  db.run(`CREATE TABLE IF NOT EXISTS "MasterItem" (
    id TEXT PRIMARY KEY, active INTEGER NOT NULL DEFAULT 1, code TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL, category TEXT NOT NULL, department TEXT NOT NULL,
    salesDef TEXT NOT NULL DEFAULT 'SALES', price REAL, plu TEXT, barcode TEXT,
    uom TEXT, folder TEXT, serviceCharge INTEGER NOT NULL DEFAULT 1,
    tax1 INTEGER NOT NULL DEFAULT 1, tax2 INTEGER NOT NULL DEFAULT 1,
    noDiscount INTEGER NOT NULL DEFAULT 1, hideReceipt INTEGER NOT NULL DEFAULT 0,
    printers TEXT, outlets TEXT, outletGroup TEXT, priceLevels TEXT,
    importedAt TEXT NOT NULL, updatedAt TEXT NOT NULL
  )`);
  // Additive migration: priceLevels stores the raw Quinos PriceLevels string
  // (e.g. "DINE IN:CSPI+CSPI-B:1100000;TAKE AWAY:CSPI:1100000;...") for items
  // imported before this column existed.
  try { db.run('ALTER TABLE "MasterItem" ADD COLUMN "priceLevels" TEXT'); } catch { /* already exists */ }
  // Second, independent registry sourced from the SAP export (List_of_Items-WINE.xlsx).
  // Deliberately NOT merged into MasterItem - SAP item numbers don't map 1:1 to
  // Quinos codes. Used only for the wine barcode-integrity cross-check.
  db.run(`CREATE TABLE IF NOT EXISTS "SapMasterItem" (
    id TEXT PRIMARY KEY, itemNo TEXT NOT NULL UNIQUE, description TEXT NOT NULL,
    subGroup TEXT, barcode TEXT, importedAt TEXT NOT NULL, updatedAt TEXT NOT NULL
  )`);
  db.run(`CREATE TABLE IF NOT EXISTS "WikiArticle" (
    id TEXT PRIMARY KEY, title TEXT NOT NULL, content TEXT NOT NULL,
    category TEXT NOT NULL DEFAULT 'General', isPinned INTEGER NOT NULL DEFAULT 0,
    createdBy TEXT NOT NULL, updatedBy TEXT, createdAt TEXT NOT NULL, updatedAt TEXT NOT NULL
  )`);
  db.run(`CREATE TABLE IF NOT EXISTS "GlossaryEntry" (
    id TEXT PRIMARY KEY, type TEXT NOT NULL, term TEXT NOT NULL,
    definition TEXT NOT NULL, defaultDefinition TEXT, grp TEXT,
    isSeeded INTEGER NOT NULL DEFAULT 0, createdAt TEXT NOT NULL, updatedAt TEXT NOT NULL
  )`);
  db.run(`CREATE TABLE IF NOT EXISTS "DiscountRequest" (
    id TEXT PRIMARY KEY,
    status TEXT NOT NULL DEFAULT 'PENDING',
    outletGroup TEXT NOT NULL,
    cashierOutlet TEXT NOT NULL,
    userId TEXT NOT NULL,
    buttonName TEXT NOT NULL,
    discountType TEXT NOT NULL,
    discountValue REAL NOT NULL,
    discountValueType TEXT NOT NULL,
    outlets TEXT NOT NULL DEFAULT '',
    applicableTo TEXT NOT NULL,
    conditions TEXT,
    remarks TEXT,
    adminNote TEXT,
    createdAt TEXT NOT NULL,
    updatedAt TEXT NOT NULL,
    updatedBy TEXT,
    doneAt TEXT
  )`);
  // Add outlets column to existing DiscountRequest tables that were created before this column was added
  const drCols = execAll(db, `PRAGMA table_info("DiscountRequest")`, []);
  if (!drCols.some((c) => c.name === 'outlets')) {
    db.run(`ALTER TABLE "DiscountRequest" ADD COLUMN outlets TEXT NOT NULL DEFAULT ''`);
  }
  db.run(`CREATE TABLE IF NOT EXISTS "OutletConfig" (
    id TEXT PRIMARY KEY, code TEXT NOT NULL UNIQUE, "group" TEXT NOT NULL,
    isActive INTEGER NOT NULL DEFAULT 1, createdAt TEXT NOT NULL, updatedAt TEXT NOT NULL
  )`);
  db.run(`CREATE TABLE IF NOT EXISTS "PrinterConfig" (
    id TEXT PRIMARY KEY, name TEXT NOT NULL UNIQUE, "group" TEXT NOT NULL,
    isActive INTEGER NOT NULL DEFAULT 1, createdAt TEXT NOT NULL, updatedAt TEXT NOT NULL
  )`);
  db.run(`CREATE TABLE IF NOT EXISTS "CategoryConfig" (
    id TEXT PRIMARY KEY, name TEXT NOT NULL UNIQUE, department TEXT NOT NULL,
    departmentCode INTEGER NOT NULL, categoryCode INTEGER NOT NULL,
    isActive INTEGER NOT NULL DEFAULT 1, createdAt TEXT NOT NULL, updatedAt TEXT NOT NULL
  )`);
  // Per-admin read state for the notification bell. A request (single PLURequest or
  // RequestBatch - both UUID-keyed, so requestId is unambiguous) is "unread" for an
  // admin until a row exists here. No row = unread; this table only tracks read-state,
  // the notification content is sourced live from the request tables.
  db.run(`CREATE TABLE IF NOT EXISTS "NotificationRead" (
    id TEXT PRIMARY KEY, adminUserId TEXT NOT NULL, requestId TEXT NOT NULL,
    readAt TEXT NOT NULL
  )`);
  db.run('CREATE UNIQUE INDEX IF NOT EXISTS "idx_notifread_admin_req" ON "NotificationRead" (adminUserId, requestId)');
  // ── Wine List module (wine catalog layered over MasterItem) ────────────────
  // SOURCE OF TRUTH: PLU code, barcode, price, folder, outlets, tax/service flags and active-per-
  // outlet all live on MasterItem and are NEVER copied here as editable data. WineMaster stores only
  // wine-specific attributes + the masterItemId link. masterItemCode/masterItemName are a denormalised
  // cache for list search/sort only (the detail view always re-reads the master row).
  db.run(`CREATE TABLE IF NOT EXISTS "WineMaster" (
    id TEXT PRIMARY KEY,
    masterItemId TEXT NOT NULL,
    masterItemCode TEXT,
    masterItemName TEXT,
    sourceRequestId TEXT,
    legacyWineCode TEXT,
    importBatchId TEXT,
    wineName TEXT NOT NULL,
    normalizedName TEXT NOT NULL DEFAULT '',
    displayName TEXT,
    producerId TEXT,
    countryId TEXT,
    regionId TEXT,
    appellationId TEXT,
    classificationId TEXT,
    wineTypeId TEXT,
    categoryId TEXT,
    subCategory1Id TEXT,
    subCategory2Id TEXT,
    bottleSizeId TEXT,
    vintage INTEGER,
    isNonVintage INTEGER NOT NULL DEFAULT 0,
    abv REAL,
    description TEXT,
    tastingNotes TEXT,
    foodPairing TEXT,
    servingTemperature TEXT,
    internalNotes TEXT,
    costPerBottle REAL,
    status TEXT NOT NULL DEFAULT 'Active',
    createdAt TEXT NOT NULL,
    createdBy TEXT,
    updatedAt TEXT NOT NULL,
    updatedBy TEXT
  )`);
  // Rule 2 (one active Master Item ↔ one active Wine Master) is enforced in application code, not by
  // a unique index: an inactive Wine Master keeps its masterItemId so history survives, which a plain
  // UNIQUE(masterItemId) would forbid. A partial index gives the DB-level guarantee for ACTIVE rows only.
  db.run(`CREATE UNIQUE INDEX IF NOT EXISTS "idx_winemaster_master_active" ON "WineMaster" (masterItemId) WHERE status = 'Active'`);
  // Rule 20 / anti-duplicate: a source request can back at most one Wine Master, ever.
  db.run(`CREATE UNIQUE INDEX IF NOT EXISTS "idx_winemaster_request" ON "WineMaster" (sourceRequestId) WHERE sourceRequestId IS NOT NULL`);
  db.run(`CREATE INDEX IF NOT EXISTS "idx_winemaster_norm" ON "WineMaster" (normalizedName)`);
  db.run(`CREATE INDEX IF NOT EXISTS "idx_winemaster_batch" ON "WineMaster" (importBatchId)`);
  // One wine can be a blend - percentage is optional (nullable) since legacy data rarely carries it.
  db.run(`CREATE TABLE IF NOT EXISTS "WineVarietal" (
    id TEXT PRIMARY KEY, wineMasterId TEXT NOT NULL, varietalId TEXT NOT NULL, percentage REAL
  )`);
  db.run(`CREATE INDEX IF NOT EXISTS "idx_winevarietal_wine" ON "WineVarietal" (wineMasterId)`);
  // Append-only. No UI path ever updates or deletes a row here.
  db.run(`CREATE TABLE IF NOT EXISTS "WineAuditLog" (
    id TEXT PRIMARY KEY, wineMasterId TEXT NOT NULL, action TEXT NOT NULL,
    fieldName TEXT, oldValue TEXT, newValue TEXT,
    performedBy TEXT, performedAt TEXT NOT NULL
  )`);
  db.run(`CREATE INDEX IF NOT EXISTS "idx_wineaudit_wine" ON "WineAuditLog" (wineMasterId)`);
  db.run(`CREATE TABLE IF NOT EXISTS "WineImportBatch" (
    id TEXT PRIMARY KEY, fileName TEXT NOT NULL, totalRows INTEGER NOT NULL DEFAULT 0,
    createdRows INTEGER NOT NULL DEFAULT 0, updatedRows INTEGER NOT NULL DEFAULT 0,
    duplicateRows INTEGER NOT NULL DEFAULT 0, failedRows INTEGER NOT NULL DEFAULT 0,
    skippedRows INTEGER NOT NULL DEFAULT 0, matchedRows INTEGER NOT NULL DEFAULT 0,
    unmatchedRows INTEGER NOT NULL DEFAULT 0,
    status TEXT NOT NULL DEFAULT 'COMPLETED', uploadedBy TEXT, uploadedAt TEXT NOT NULL,
    completedAt TEXT, rolledBackAt TEXT, rolledBackBy TEXT
  )`);
  db.run(`CREATE TABLE IF NOT EXISTS "WineImportError" (
    id TEXT PRIMARY KEY, importBatchId TEXT NOT NULL, rowNumber INTEGER NOT NULL,
    wineName TEXT, pluCode TEXT, barcode TEXT, error TEXT NOT NULL,
    recommendation TEXT, createdAt TEXT NOT NULL
  )`);
  db.run(`CREATE INDEX IF NOT EXISTS "idx_wineimporterror_batch" ON "WineImportError" (importBatchId)`);
  // One generic table for every wine reference list (PRODUCER, COUNTRY, REGION, APPELLATION,
  // VARIETAL, WINE_TYPE, CATEGORY, SUB_CATEGORY, BOTTLE_SIZE, CLASSIFICATION). Chosen over ten
  // near-identical tables so one CRUD route + one dedupe rule covers all of them. normalizedName is
  // uniquely indexed per type, which is what blocks "Bouchard Père & Fils" vs "BOUCHARD PERE & FILS".
  db.run(`CREATE TABLE IF NOT EXISTS "WineMasterData" (
    id TEXT PRIMARY KEY, type TEXT NOT NULL, code TEXT, name TEXT NOT NULL,
    normalizedName TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'Active',
    createdAt TEXT NOT NULL, createdBy TEXT, updatedAt TEXT NOT NULL, updatedBy TEXT
  )`);
  db.run(`CREATE UNIQUE INDEX IF NOT EXISTS "idx_winemasterdata_type_norm" ON "WineMasterData" (type, normalizedName)`);
  fs.writeFileSync(dbPath, Buffer.from(db.export()));
  g.__sqljsDb = db;
  return db;
}

async function getDb() {
  if (g.__sqljsDb) return g.__sqljsDb;
  // Single shared init promise - concurrent callers await the same one instead
  // of each running a full read/migrate/write pass. Reset on failure so a
  // transient error doesn't permanently wedge the cached rejection.
  if (!g.__sqljsInit) {
    g.__sqljsInit = initDb().catch((err) => { g.__sqljsInit = undefined; throw err; });
  }
  return g.__sqljsInit;
}


// Write lock - chains writes sequentially so concurrent requests don't race.
let writeQueue: Promise<unknown> = Promise.resolve();

async function withWriteLock<T>(fn: (db: ReturnType<typeof getDb> extends Promise<infer U> ? U : never) => T | Promise<T>): Promise<T> {
  const task = writeQueue.then(async () => {
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    const db: any = await getDb();
    const result = await fn(db);
    fs.writeFileSync(resolveDbPath(), Buffer.from(db.export()));
    return result;
  });
  writeQueue = task.catch(() => {});
  return task as Promise<T>;
}

// Internal DB primitives re-exported for sibling module files (currently lib/wineDb.ts). They MUST
// be imported from here rather than re-implemented: getDb owns the single shared init promise and
// withWriteLock owns the single serialising write queue, so a module that opened its own handle
// would race the main one and lose writes.
export const _internal = {
  getDb,
  withWriteLock,
  execAll: (db: unknown, sql: string, params: unknown[] = []) => execAll(db, sql, params),
  execFirst: (db: unknown, sql: string, params: unknown[] = []) => execFirst(db, sql, params),
  newId,
  nowIso,
  normBool,
  normStr,
};

// ── Row utilities ────────────────────────────────────────────────────────────

function rowToObj(columns: string[], values: unknown[]): Record<string, unknown> {
  const obj: Record<string, unknown> = {};
  columns.forEach((col, i) => { obj[col] = values[i]; });
  return obj;
}

// eslint-disable-next-line @typescript-eslint/no-explicit-any
function execFirst(db: any, sql: string, params: unknown[] = []): Record<string, unknown> | null {
  const results = db.exec(sql, params);
  if (!results.length || !results[0].values.length) return null;
  return rowToObj(results[0].columns, results[0].values[0]);
}

// eslint-disable-next-line @typescript-eslint/no-explicit-any
function execAll(db: any, sql: string, params: unknown[] = []): Record<string, unknown>[] {
  const results = db.exec(sql, params);
  if (!results.length) return [];
  const { columns, values } = results[0];
  return (values as unknown[][]).map((row) => rowToObj(columns, row));
}

function normBool(v: unknown): boolean { return v === 1 || v === true; }
function normStr(v: unknown): string | null { return v == null ? null : String(v); }
function newId(): string { return crypto.randomUUID(); }
function nowIso(): string { return new Date().toISOString(); }

