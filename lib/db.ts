// Highest numeric barcode across both registries (MasterItem + SapMasterItem). Non-digit
// characters are stripped and the remainder parsed as an integer; the max across all rows is
// returned (0 when neither table has a usable barcode). Used by the Cost Control sequential
// barcode-suggestion fallback when no SAP NCK match is found.
export async function getMaxExistingBarcode(): Promise<number> {
  try {
    const db = await getDb();
    const rows = execAll(db, `
      SELECT barcode FROM "MasterItem"    WHERE barcode IS NOT NULL AND TRIM(barcode) != ''
      UNION ALL
      SELECT barcode FROM "SapMasterItem" WHERE barcode IS NOT NULL AND TRIM(barcode) != ''
    `);
    let max = 0;
    for (const r of rows) {
      const digits = String(r.barcode ?? '').replace(/\D/g, '');
      if (!digits) continue;
      const n = parseInt(digits, 10);
      if (!Number.isNaN(n) && n > max) max = n;
    }
    return max;
  } catch (err) {
    console.error('[db] getMaxExistingBarcode failed:', err);
    return 0;
  }
}

