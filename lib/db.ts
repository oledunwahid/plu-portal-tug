// ── Admin request statistics ──────────────────────────────────────────────────
//
// One source of truth for every count the admin Dashboard and Export page show, so a number never
// means two different things in two places.
//
// Counting unit = one ITEM the admin has to process:
//   • source 'single' → one PLURequest row
//   • source 'batch'  → one RequestBatchItem row (NOT one batch) - this matches what the Export
//     page actually lists, since batches are flattened to their items there.
//   • source 'all'    → the sum of both.
// A batch's lifecycle status lives on the batch, so all of its items inherit it.

export interface RequestTypeStat {
  pending: number;
  exported: number;
  done: number;
  /** NEW_ITEM awaiting cost-control confirmation - not yet in the admin's queue. */
  costControl: number;
  rejected: number;
  /** Every row regardless of status: pending + exported + done + costControl + rejected. */
  total: number;
}

export type RequestStatsSource = 'single' | 'batch' | 'all';

export interface RequestStatsFilters {
  source?: RequestStatsSource;
  outletGroup?: string;
  from?: string;
  to?: string;
  search?: string;
}

const STATS_TYPES = ['NEW_ITEM', 'UPDATE_PRICE', 'UPDATE_NAME', 'UPDATE_PRINTER', 'REMOVE_PLU'] as const;

function emptyTypeStat(): RequestTypeStat {
  return { pending: 0, exported: 0, done: 0, costControl: 0, rejected: 0, total: 0 };
}

// Map a stored status string onto the stat bucket it belongs to. Unknown statuses still land in
// `total` but in no bucket, so a stray value can never be silently reported as "pending".
function statBucket(status: string): keyof RequestTypeStat | null {
  switch (status) {
    case 'PENDING': return 'pending';
    case 'EXPORTED': return 'exported';
    case 'DONE': return 'done';
    case 'PENDING_COST_CONTROL': return 'costControl';
    case 'REJECTED': return 'rejected';
    default: return null;
  }
}

export async function getRequestStatsByType(
  filters: RequestStatsFilters = {},
): Promise<Record<string, RequestTypeStat>> {
  const result: Record<string, RequestTypeStat> = {};
  for (const t of STATS_TYPES) result[t] = emptyTypeStat();

  const source = filters.source ?? 'all';
  try {
    const db = await getDb();
    const scope = { outletGroup: filters.outletGroup, from: filters.from, to: filters.to, search: filters.search };

    const add = (type: string, status: string, count: number) => {
      if (!result[type]) return; // ignore request types outside the admin's five sections
      const bucket = statBucket(status);
      if (bucket) result[type][bucket] += count;
      result[type].total += count;
    };

    if (source === 'single' || source === 'all') {
      const { conditions, params } = buildPLUConditions(scope, 'pr');
      const where = conditions.length ? `WHERE ${conditions.join(' AND ')}` : '';
      const rows = execAll(db, `
        SELECT pr.requestType as t, pr.status as s, COUNT(*) as cnt
        FROM "PLURequest" pr ${where} GROUP BY pr.requestType, pr.status
      `, params);
      for (const r of rows) add(String(r.t), String(r.s), Number(r.cnt));
    }

    if (source === 'batch' || source === 'all') {
      const { conditions, params } = buildBatchConditions(scope, 'rb');
      const where = conditions.length ? `WHERE ${conditions.join(' AND ')}` : '';
      const rows = execAll(db, `
        SELECT rb.requestType as t, rb.status as s, COUNT(bi.id) as cnt
        FROM "RequestBatch" rb JOIN "RequestBatchItem" bi ON bi.batchId = rb.id
        ${where} GROUP BY rb.requestType, rb.status
      `, params);
      for (const r of rows) add(String(r.t), String(r.s), Number(r.cnt));
    }

    return result;
  } catch (err) {
    console.error('[db] getRequestStatsByType failed:', err);
    throw err; // the caller returns 500 - an all-zero fallback would read as "no work left"
  }
}

