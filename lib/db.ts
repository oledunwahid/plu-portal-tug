// Insert read-state rows (idempotent via the unique index) for this admin. Returns the
// number of newly-inserted rows.
export async function markNotificationsRead(adminUserId: string, requestIds: string[]): Promise<number> {
  const ids = Array.from(new Set(requestIds.filter((r) => typeof r === 'string' && r.trim())));
  if (ids.length === 0) return 0;
  return withWriteLock((db) => {
    const now = nowIso();
    let inserted = 0;
    for (const requestId of ids) {
      db.run(
        'INSERT OR IGNORE INTO "NotificationRead" (id, adminUserId, requestId, readAt) VALUES (?,?,?,?)',
        [newId(), adminUserId, requestId, now]
      );
      // db.getRowsModified() reflects the last statement; count only real inserts.
      if (typeof db.getRowsModified === 'function' && db.getRowsModified() > 0) inserted += 1;
    }
    return inserted;
  });
}

