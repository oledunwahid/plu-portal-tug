/**
 * Partial update of a MasterItem by id. Only the provided fields are written.
 * `code` is intentionally not updatable (it is the import key / immutable identifier).
 * Returns the updated row, or null if no item with that id exists.
 */
export async function updateMasterItem(id: string, fields: MasterItemUpdateInput): Promise<DbMasterItem | null> {
  return withWriteLock((db) => {
    const existing = execFirst(db, 'SELECT id FROM "MasterItem" WHERE id = ?', [id]);
    if (!existing) return null;

    const BOOL_COLS = new Set(['active', 'serviceCharge', 'tax1', 'tax2', 'noDiscount', 'hideReceipt']);
    const ALLOWED = [
      'active', 'name', 'category', 'department', 'salesDef', 'price', 'plu', 'barcode',
      'uom', 'folder', 'serviceCharge', 'tax1', 'tax2', 'noDiscount', 'hideReceipt',
      'printers', 'outlets', 'outletGroup', 'priceLevels',
    ] as const;

    const sets: string[] = [];
    const params: unknown[] = [];
    for (const col of ALLOWED) {
      if (!(col in fields)) continue;
      const val = (fields as Record<string, unknown>)[col];
      sets.push(`${col}=?`);
      if (BOOL_COLS.has(col)) params.push(val ? 1 : 0);
      else params.push(val ?? null);
    }
    sets.push('updatedAt=?');
    params.push(nowIso(), id);
    db.run(`UPDATE "MasterItem" SET ${sets.join(',')} WHERE id=?`, params);

    const row = execFirst(db, 'SELECT * FROM "MasterItem" WHERE id = ?', [id]);
    return row ? rowToMasterItem(row) : null;
  });
}

/**
 * Rewrite MasterItem.priceLevels for many items in ONE write-lock pass.
 *
 * withWriteLock re-serialises the whole SQLite file to disk on every call, so calling
 * updateMasterItem() per item would rewrite a multi-megabyte file once per row. This does the
 * whole set inside a single lock and a single flush.
 *
 * Only the priceLevels column (plus updatedAt) is touched - name, category, base price, outlets
 * and every flag are left exactly as they were. Codes with no master row are skipped and
 * reported back rather than failing the batch.
 */
export async function updateMasterItemsPriceLevels(
  updates: Map<string, string>,
): Promise<{ updated: number; missing: string[] }> {
  if (updates.size === 0) return { updated: 0, missing: [] };
  return withWriteLock((db) => {
    const now = nowIso();
    const missing: string[] = [];
    let updated = 0;
    updates.forEach((priceLevels, code) => {
      const existing = execFirst(db, 'SELECT id FROM "MasterItem" WHERE code = ?', [code]);
      if (!existing) { missing.push(code); return; }
      db.run('UPDATE "MasterItem" SET priceLevels=?, updatedAt=? WHERE code=?',
        [priceLevels === '' ? null : priceLevels, now, code]);
      updated += 1;
    });
    return { updated, missing };
  });
}

