// Cost Control history: NEW_ITEM requests that have already been through the cost-control stage —
// i.e. confirmed (confirmedBarcode set, now moved on to PENDING/EXPORTED/DONE) or rejected.
// Items still awaiting review (PENDING_COST_CONTROL) are the live queue, fetched separately via
// getPLURequests({ status: 'PENDING_COST_CONTROL' }). Optional date (createdAt) + outlet filters.
