const GC_SEP = '|||'; // GROUP_CONCAT separator safe against commas in names/outlets

function barcodeFormat(barcode: string): string {
  const b = barcode.trim();
  if (b.endsWith('11')) return 'NCK';
  if (/^\d{6,7}$/.test(b)) return 'Format lama (kemungkinan NCK)';
  return 'Standard';
}

function dedupeSemiList(values: (string | null | undefined)[]): string[] {
  const out = new Set<string>();
  for (const v of values) {
    if (!v) continue;
    for (const part of String(v).split(/[;,]/)) {
      const t = part.trim();
      if (t) out.add(t);
    }
  }
  return Array.from(out);
}

export async function getDataQualityReport(): Promise<DataQualityReport> {
  const db = await getDb();

  // 1. Duplicate candidates - items sharing prefix(1-3) + dept(4-5) + cat(6-8)
  //    + price + priceLevels. Grouping is done in SQL; we only fetch rows that
  //    actually belong to a group of size > 1.
  const dupRows = execAll(db, `
    SELECT m.* FROM "MasterItem" m
    JOIN (
      SELECT substr(code,1,3) p, substr(code,4,2) d, substr(code,6,3) c,
             COALESCE(price,-1) pr, trim(COALESCE(priceLevels,'')) pl
      FROM "MasterItem"
      GROUP BY p, d, c, pr, pl
      HAVING COUNT(*) > 1
    ) g
      ON substr(m.code,1,3) = g.p
     AND substr(m.code,4,2) = g.d
     AND substr(m.code,6,3) = g.c
     AND COALESCE(m.price,-1) = g.pr
     AND trim(COALESCE(m.priceLevels,'')) = g.pl
    ORDER BY g.p, g.d, g.c, g.pr, g.pl, m.code
  `, []);
  const duplicates: DbMasterItem[][] = [];
  let lastKey = '';
  for (const row of dupRows) {
    const item = rowToMasterItem(row);
    const key = `${item.code.substring(0, 3)}|${item.code.substring(3, 5)}|${item.code.substring(5, 8)}|${item.price ?? -1}|${(item.priceLevels ?? '').trim()}`;
    if (key !== lastKey) { duplicates.push([]); lastKey = key; }
    duplicates[duplicates.length - 1].push(item);
  }

  // 2. Price gaps - same name (case-insensitive trim), differing price.
  const gapRows = execAll(db, `
    SELECT MAX(name) AS name,
           GROUP_CONCAT(code, '${GC_SEP}') AS codes,
           GROUP_CONCAT(COALESCE(outlets,''), '${GC_SEP}') AS outlets,
           MIN(price) AS minPrice, MAX(price) AS maxPrice
    FROM "MasterItem"
    WHERE price IS NOT NULL
    GROUP BY lower(trim(name))
    HAVING COUNT(DISTINCT price) > 1
    ORDER BY (MAX(price) - MIN(price)) DESC
  `, []);
  const priceGaps: PriceGapRow[] = gapRows.map((r) => {
    const minPrice = Number(r.minPrice);
    const maxPrice = Number(r.maxPrice);
    return {
      name: String(r.name),
      codes: String(r.codes ?? '').split(GC_SEP).filter(Boolean),
      minPrice, maxPrice, gap: maxPrice - minPrice,
      outlets: dedupeSemiList(String(r.outlets ?? '').split(GC_SEP)),
    };
  });

  // 3. Duplicate barcodes - two or more active items with the same non-empty barcode.
  const barcodeRows = execAll(db, `
    SELECT barcode,
           COUNT(*) AS cnt,
           GROUP_CONCAT(code, '${GC_SEP}') AS codes,
           GROUP_CONCAT(name, '${GC_SEP}') AS names
    FROM "MasterItem"
    WHERE active = 1 AND barcode IS NOT NULL AND trim(barcode) <> ''
    GROUP BY barcode
    HAVING COUNT(*) > 1
  `, []);
  const formatRank: Record<string, number> = { 'Format lama (kemungkinan NCK)': 0, 'NCK': 1, 'Standard': 2 };
  const duplicateBarcodes: BarcodeDupRow[] = barcodeRows
    .map((r) => {
      const barcode = String(r.barcode);
      return {
        barcode,
        count: Number(r.cnt),
        codes: String(r.codes ?? '').split(GC_SEP).filter(Boolean),
        names: String(r.names ?? '').split(GC_SEP).filter(Boolean),
        format: barcodeFormat(barcode),
      };
    })
    .sort((a, b) => (formatRank[a.format] ?? 3) - (formatRank[b.format] ?? 3));

  // 4. Trial / placeholder items - active items whose name looks like test data.
  //    SQLite LIKE is case-insensitive for ASCII, so keyword matches need no upper().
  const trialRows = execAll(db, `
    SELECT * FROM "MasterItem"
    WHERE active = 1 AND (
      name LIKE '--%' OR name LIKE '- %' OR name LIKE '# %'
      OR name LIKE '%HOLD%' OR name LIKE '%PROCESS%' OR name LIKE '%TEST%'
      OR name LIKE '%TRIAL%' OR name LIKE '%DUMMY%' OR name LIKE '%START%'
      OR name = '-' OR name = '--'
    )
    ORDER BY name ASC
  `, []);
  const trialItems = trialRows.map(rowToMasterItem);

  return { duplicates, priceGaps, duplicateBarcodes, trialItems };
}

